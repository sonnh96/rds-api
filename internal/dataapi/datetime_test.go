// The PostgreSQL driver decodes timestamps for us, so the time.Time forms have
// to agree with the string forms.
func TestDatetimeValueFormsMatchStringForms(t *testing.T) {
	instant := time.Date(2021, 3, 10, 22, 41, 4, 123456000, time.FixedZone("+02", 2*60*60))

	if got, want := ConvertOffsetDatetimeValueToUTC(instant), "2021-03-10 20:41:04.123456"; got != want {
		t.Errorf("ConvertOffsetDatetimeValueToUTC = %q, want %q", got, want)
	}

	naive := time.Date(2021, 3, 10, 20, 41, 4, 20000000, time.UTC)
	if got, want := FormatDatetimeValue(naive), "2021-03-10 20:41:04.02"; got != want {
		t.Errorf("FormatDatetimeValue = %q, want %q", got, want)
	}
}

// A bare date must not have its "-10" mistaken for a UTC offset.
func TestConvertOffsetDatetimeToUTCIgnoresDateDashes(t *testing.T) {
	got, err := ConvertOffsetDatetimeToUTC("2021-03-10 20:41:04.123456")
	if err != nil {
		t.Fatalf("unexpected error: %v", err)
	}
	if want := "2021-03-10 20:41:04.123456"; got != want {
		t.Errorf("got %q, want %q", got, want)
	}
}
